/**
 * ---------------------------------------------------------------------------
 * COMMITTED DEMO INDEX — WIRE FORMAT
 * ---------------------------------------------------------------------------
 * `public/demo-data/index.json` is the deployed equivalent of
 * `.scanlab/manifest.json`. It exists because the two cannot be the same file:
 *
 *   - `.scanlab/manifest.json` is gitignored, holds absolute Windows paths, and
 *     is read by API routes that call `fs`. None of that survives deployment.
 *   - The Cloudflare Worker has no filesystem and no `SCANLAB_DATA_ROOT`, so a
 *     deployed study's pixels can only come from `public/` as static assets,
 *     decoded in the browser.
 *
 * So the index describes the *committed* studies under `public/demo-data` in
 * terms of public URLs plus the small amount of measured geometry the browser
 * would otherwise need `fs` and an affine solver to work out for itself.
 *
 * It is NOT a second dataset system. It is generated by `scripts/demo-index.ts`
 * running the real adapters (`lib/dataset/adapters/*`) over `public/demo-data`,
 * and `lib/demo/expand.ts` turns it straight back into the same `DatasetStudy[]`
 * the manifest holds, so everything downstream — `toAppStudy`, the report
 * parser, the viewer, the findings layer — is the existing pipeline unchanged.
 *
 * Field names are short because this file is downloaded by every visitor.
 *
 * No `fs`, no `path`, no imports outside `lib/dataset/types` — this module is
 * imported by both the generator and the browser.
 * ---------------------------------------------------------------------------
 */

import {
  DatasetSourceId,
  ImageSourceKind,
  NormalizedModality,
  SliceOrientation,
  StudyReport,
} from "../dataset/types";

/**
 * Bumped whenever the shape below changes incompatibly. `lib/demo/load.ts`
 * refuses an index whose version it does not recognize rather than rendering
 * half a study from fields that have moved.
 */
export const DEMO_INDEX_VERSION = 1;

/** Served from `public/`, so this is both the repo path and the deployed URL. */
export const DEMO_INDEX_URL = "/demo-data/index.json";

/**
 * A byte range inside a ZIP archive.
 *
 * Every entry in the ten committed MRI archives was measured to use method 0
 * (STORED), which means the `.nii.gz` member sits in the archive uncompressed
 * and verbatim: a `Range: bytes=off-(off+len-1)` request returns exactly the
 * member's own bytes, with no zip inflate step in the browser. That is what
 * makes serving a 3–5 MB volume out of a 15–21 MB committed archive practical
 * without unpacking 700 MB of NIfTI into `public/`.
 */
export interface DemoZipRange {
  /** Absolute offset of the member's first byte within the archive. */
  off: number;
  len: number;
}

/**
 * One screen axis of one plane: which voxel axis it walks, and whether it walks
 * it backwards. Serialized as a pair to keep the index small — this appears
 * three times per plane, three planes per volume.
 *
 * Mirrors `AxisRef` in `image-render.ts`, which is derived from the volume's own
 * affine. Measuring it at generation time is the whole point: the browser then
 * reslices by indexing, and never has to interpret a qform/sform matrix.
 */
export type DemoAxis = [axis: 0 | 1 | 2, flip: boolean];

/** The three reconstructable anatomical planes — mirrors `MprPlane` in `image-render.ts`. */
export type DemoPlane = "Axial" | "Coronal" | "Sagittal";

/** Mirrors `NiftiPlaneGeometry`; `w`/`ht` are the rendered pixel dimensions of the plane. */
export interface DemoPlaneGeometry {
  n: number;
  w: number;
  ht: number;
  t: DemoAxis;
  h: DemoAxis;
  v: DemoAxis;
}

/**
 * A NIfTI volume the browser will decode itself, with everything needed to
 * render any plane of it measured server-side at generation time.
 */
export interface DemoVolume {
  /** Public URL of the container: the `.nii.gz` itself, or the archive when `zip` is set. */
  url: string;
  /** Present when `url` points at a ZIP archive rather than the volume — see `DemoZipRange`. */
  zip?: DemoZipRange;
  dims: [number, number, number];
  /** NIFTI1.TYPE_* code, fed to `niftiTypedArray`. */
  datatype: number;
  slope: number;
  inter: number;
  /** The server's own `computeVolumeWindow` result, so client and server grayscale agree. */
  win: { lo: number; range: number };
  planes: Partial<Record<DemoPlane, DemoPlaneGeometry>>;
}

/**
 * One series, in the same two representations `DatasetSeries` uses: `files` for
 * one-file-per-slice sources, `vol` + `plane` for a run of frames out of a
 * single volumetric container.
 */
export interface DemoSeries {
  id: string;
  label: string;
  orientation: SliceOrientation;
  /** Slice count. Always equals `files.length` when `files` is set. */
  n: number;
  kind: ImageSourceKind;
  /** Public URLs, one per slice, in slice order. Set for `raster` and `dicom`. */
  files?: string[];
  /** Key into `DemoStudy.volumes`. Set for `nifti`. */
  vol?: string;
  /** Which plane of `vol` this series walks. */
  plane?: DemoPlane;
  w?: number;
  h?: number;
}

/**
 * A committed demo study. Field-for-field a reduced `DatasetStudy`: `expand.ts`
 * restores the full shape, and nothing downstream knows the difference.
 */
export interface DemoStudy {
  id: string;
  dataset: DatasetSourceId;
  code: string;
  srcId: string;
  alias: string;
  modality: NormalizedModality;
  bodyRegion?: string;
  date?: string;
  /** Only when the committed source data states it. Never generated here. */
  age?: number;
  sex?: "M" | "F" | "Other";
  /** Kilograms, only when the source states it — PET's `metadata.json` does. */
  weightKg?: number;
  series: DemoSeries[];
  volumes?: Record<string, DemoVolume>;
  /** Verbatim from the study's own committed `report.json` / report file. */
  report?: StudyReport;
}

/**
 * A study whose images are deliberately absent from the deployed build, with the
 * reason stated.
 *
 * Two MRI archives (IQT6Z5U6WE 46.3 MiB, KNCH35VQQ5 35.8 MiB) exceed
 * Cloudflare's 25 MiB per-asset limit and were removed from Git on purpose;
 * their `report.json` is still committed. Listing them here rather than as
 * studies with zero series keeps them out of the studies list — a card that
 * cannot open anything is worse than no card — while keeping the omission
 * visible instead of silent.
 */
export interface DemoOmission {
  srcId: string;
  dataset: DatasetSourceId;
  reason: string;
}

export interface DemoIndex {
  version: number;
  generatedAt: string;
  /** Which adapter build produced this, for the same reason `DatasetManifest.builderVersion` exists. */
  builderVersion: number;
  studies: DemoStudy[];
  omitted: DemoOmission[];
}

/**
 * ---------------------------------------------------------------------------
 * URL MARKERS
 * ---------------------------------------------------------------------------
 * A demo slice URL has to say how to decode itself, because the thing fetching
 * it is a plain `<img>`-shaped code path that only ever had a URL to go on. The
 * markers are query parameters on the asset's own URL:
 *
 *   /demo-data/chest-xray/X/X.png                     → raster, load directly
 *   /demo-data/ct/PA0_ct_chest/1-01.dcm?dcm=1         → parse DICOM, window, draw
 *   /demo-data/mri/4IJW45J4TC.zip?nii=<key>&p=C&f=12  → NIfTI, coronal, frame 12
 *
 * `nii` is a registry key rather than the geometry itself: the alternative is a
 * URL carrying dims, affine axes and a window, which would be ~200 characters
 * repeated for every one of a 512-slice plane's frames. The registry is
 * populated from the same index the URL came from — see `lib/demo/registry.ts`.
 *
 * `p` is spelled out in the URL rather than looked up because a plane is a
 * property of the *series*, not of the volume: all three MPR planes of one MRI
 * volume share a single registry entry, and one character is cheaper than three
 * entries plus a series-to-plane map.
 */
export const DEMO_DICOM_PARAM = "dcm";
export const DEMO_NIFTI_PARAM = "nii";
export const DEMO_PLANE_PARAM = "p";
export const DEMO_FRAME_PARAM = "f";
/** Optional downscale hint, honoured by the decoder for thumbnails. */
export const DEMO_WIDTH_PARAM = "w";

/** URL spelling of a plane name — one character, because it appears in every slice URL. */
export const DEMO_PLANE_CODE: Record<DemoPlane, string> = {
  Axial: "A",
  Coronal: "C",
  Sagittal: "S",
};

export function demoPlaneFromCode(code: string | null): DemoPlane | undefined {
  if (code === "A") return "Axial";
  if (code === "C") return "Coronal";
  if (code === "S") return "Sagittal";
  return undefined;
}

/** True for any URL this module's decoder, rather than the browser, has to handle. */
export function isDemoDecodeUrl(url: string): boolean {
  return (
    url.includes(`${DEMO_DICOM_PARAM}=1`) ||
    url.includes(`${DEMO_NIFTI_PARAM}=`)
  );
}
